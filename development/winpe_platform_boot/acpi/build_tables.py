"""Build honest bring-up ACPI tables from checked board facts, not device IDs
borrowed from a different SoC. These tables do not supply missing OS drivers.
Run with python3 inside WSL (iasl required).
"""
import pathlib, struct, subprocess, hashlib, json, re
ROOT=pathlib.Path(__file__).resolve().parent
OUT=ROOT.parent/'evidence'/'acpi'
OUT.mkdir(exist_ok=True)
DTS=pathlib.Path('/mnt/c/MOTO_G20_WOA_LAB/04_DEVICE_TREE/live_fdt.dts')
DMESG=pathlib.Path('/mnt/c/MOTO_G20_WOA_LAB/03_ROOT_DUMPS/dmesg_full.txt')
dt=DTS.read_text(); dm_bytes=DMESG.read_bytes()
dm=dm_bytes.decode('utf-16' if dm_bytes.startswith((b'\xff\xfe',b'\xfe\xff')) else 'utf-8')
def block(name):
    match=re.search(r'^\s*'+re.escape(name)+r'\s*\{',dt,re.M)
    assert match, name
    start=match.end(); nesting=1; end=start
    while nesting:
        nesting += (dt[end]=='{')-(dt[end]=='}');end+=1
    return dt[start:end-1]
def cells(node,key):
    match=re.search(re.escape(key)+r'\s*=\s*<([^>]+)>;',node)
    assert match,key
    return [int(x,0) for x in match.group(1).split()]
gic=block('interrupt-controller@12000000')
assert '"arm,gic-v3"' in gic
assert cells(gic,'reg')==[0,0x12000000,0,0x20000,0,0x12040000,0,0x100000]
assert cells(gic,'redistributor-stride')==[0,0x20000]
assert cells(block('timer'),'interrupts')==[1,13,4,1,14,4,1,11,4,1,10,4]
assert '"arm,psci-0.2"' in block('psci') and '"smc"' in block('psci')
for i in range(8):
    cpu=block('cpu@'+format(i*0x100,'x'))
    assert cells(cpu,'reg')==[0,i*0x100] and '"psci"' in cpu
    assert 'found redistributor '+format(i*0x100,'x')+' region 0:0x%016x'%(0x12040000+i*0x20000) in dm
assert 'PSCIv1.0 detected' in dm and '26.00MHz (phys)' in dm
def table(sig,revision,payload):
    header=struct.pack('<4sIBB6s8sI4sI',sig,36+len(payload),revision,0,b'G20LAB',b'UMS512  ',1,b'G20L',1)
    data=bytearray(header+payload);data[9]=(-sum(data))&255
    assert sum(data)%256==0
    return data
fadt=table(b'FACP',6,bytes(276-36))
fadt[45]=8 # Tablet profile (ACPI enumeration value 8).
struct.pack_into('<H',fadt,109,(1<<5)|(1<<2)) # No legacy CMOS RTC or VGA.
struct.pack_into('<I',fadt,112,1<<20) # Hardware-reduced; do not claim low-power S0.
struct.pack_into('<H',fadt,129,1) # PSCI compliant, SMC conduit.
fadt[131]=3
fadt[9]=0;fadt[9]=(-sum(fadt))&255
giccs=[]
for i in range(8):
    entry=bytearray(80)
    struct.pack_into('<BBHIIIII',entry,0,11,80,0,i,i,1,0,144+i)
    # Reserved, parked address, legacy CPU/GICV/GICH addresses remain zero.
    struct.pack_into('<I',entry,56,25) # VGIC maintenance PPI 9 + 16, level.
    struct.pack_into('<Q',entry,68,i*0x100) # MPIDR; redistributors via GICR range.
    giccs.append(entry)
gicd=struct.pack('<BBHIQIB3s',12,24,0,0,0x12000000,0,3,b'\0'*3)
gicr=struct.pack('<BBHQI',14,16,0,0x12040000,0x100000)
madt=table(b'APIC',5,bytes(8)+b''.join(giccs)+gicd+gicr)
gtdt_payload=struct.pack('<QI8IQ4I',0xffffffffffffffff,0,29,0,30,0,27,0,26,0,0xffffffffffffffff,0,0,0,0)
gtdt=table(b'GTDT',3,gtdt_payload)
assert len(gtdt)==104
asl='''// SPDX-License-Identifier: BSD-2-Clause-Patent
// Bring-up namespace: actual processors only. No invented SD/UART/USB IDs.
DefinitionBlock ("", "DSDT", 2, "G20LAB", "UMS512", 1)
{
    Scope (\\_SB)
    {
'''
for i in range(8):
    asl+='''        Device (CP%02d) {
            Name (_HID, "ACPI0007")
            Name (_UID, %d)
            Name (_STA, 0x0F)
        }
'''%(i,i)
asl+='    }\n}\n'
(ROOT/'Dsdt.asl').write_text(asl)
build=subprocess.run(['iasl','-we','-p',str(OUT/'Dsdt'),str(ROOT/'Dsdt.asl')],text=True,capture_output=True)
(OUT/'iasl_compile.txt').write_text(build.stdout+build.stderr)
assert build.returncode==0,build.stdout+build.stderr
dsdt=(OUT/'Dsdt.aml').read_bytes()
tables={'Dsdt':dsdt,'Fadt':fadt,'Madt':madt,'Gtdt':gtdt}
header='/* SPDX-License-Identifier: BSD-2-Clause-Patent */\n/* Generated by build_tables.py; hardware facts checked against DT and Android dmesg. */\n'
manifest={}
for name,data in tables.items():
    assert struct.unpack_from('<I',data,4)[0]==len(data) and sum(data)%256==0
    (OUT/(name+'.bin')).write_bytes(data)
    header+='STATIC CONST UINT8 m%sTemplate[] = {\n'%name
    header+='\n'.join('  '+', '.join('0x%02x'%x for x in data[i:i+16])+',' for i in range(0,len(data),16))+'\n};\n'
    manifest[name]={'size':len(data),'sha256':hashlib.sha256(data).hexdigest()}
    disasm=subprocess.run(['iasl','-d',str(OUT/(name+'.bin'))],text=True,capture_output=True)
    (OUT/(name+'_iasl_decode.txt')).write_text(disasm.stdout+disasm.stderr)
    assert disasm.returncode==0,disasm.stderr
(ROOT/'MotoG20AcpiTables.generated.h').write_text(header)
(OUT/'manifest.json').write_text(json.dumps({'tables':manifest,'dts_sha256':hashlib.sha256(DTS.read_bytes()).hexdigest(),
    'dmesg_sha256':hashlib.sha256(DMESG.read_bytes()).hexdigest(),
    'known_missing':['DBG2/SPCR: Unisoc UART Windows compatibility not demonstrated',
       'TAD/RTC, power, thermal, sleep and device drivers not implemented',
       'No assertion that this minimal set is Windows-compliant or sufficient for WinPE']},indent=2)+'\n')
print(json.dumps(manifest))
