#define MOTO_G20_MMU3C2H_INPUT_SIZE              0xC0U
#define MOTO_G20_MMU3C2H_SCTLR_EL2_OFFSET        0x60U
#define MOTO_G20_MMU3C2H_DISPATCHER_SIZE          0x0CU
#define MOTO_G20_MMU3C2H_EXPECTED_BRK_ESR         0x00000000F20003B2ULL
#define MOTO_G20_MMU3C2H_RECURSION_SENTINEL       0x000000004D33C2C2ULL
