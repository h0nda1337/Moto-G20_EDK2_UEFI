#define MOTO_G20_MMU3C2H_REMAINING_RESERVE        0xDB0U
#define MOTO_G20_MMU3C2H_LATE_RESERVE_REMAINING   0x20CU

STATIC_ASSERT (
  sizeof (MOTO_G20_TELEMETRY_V2_INPUT) == MOTO_G20_MMU3C2H_INPUT_SIZE,
  "MMU3C2H telemetry input ABI size changed"
  );
STATIC_ASSERT (
  OFFSET_OF (MOTO_G20_TELEMETRY_V2_INPUT, SctlrEl2) ==
    MOTO_G20_MMU3C2H_SCTLR_EL2_OFFSET,
  "MMU3C2H SCTLR_EL2 dispatcher offset changed"
  );

